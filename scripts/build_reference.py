"""Render the reference knowledge base from markdown into offline HTML.

Run:  python scripts/build_reference.py           # write the generated files
      python scripts/build_reference.py --check    # fail if any are stale

Why this exists
---------------
The reference area under `docs/reference/` is a living document: a growing set
of notes, interview Q&A, and an annotated resource list. It has to be readable
two ways at once -- as markdown on GitHub, and as a page you can open straight
off disk after forking the repo, with no server and no build step for the
reader (the same `file://` promise the lessons make).

Keeping two hand-written copies in sync is a losing game, so there is exactly
one source of truth -- the markdown -- and this script renders the HTML from
it. `--check` re-renders in memory and compares against what is committed, so
`make check` fails the build if someone edited a note and forgot to regenerate.
That is the same build-and-gate shape the rest of this repo uses everywhere.

What is source and what is generated
------------------------------------
Under `docs/reference/`:

  _home.md            source: the intro shown on the reference home
  resources.md        source: the annotated resource catalogue
  notes/<slug>.md     source: one note per file
  interview/<slug>.md source: one Q&A set per file

  README.md           GENERATED: the home, as markdown, for GitHub
  index.html          GENERATED: the home, as an offline page
  <slug>.html         GENERATED: one page per source .md, beside it

Files whose name starts with `_` are sources or templates and are never
published as their own entry (so `_template.md` shows people the format without
appearing in the index).

The markdown this understands
-----------------------------
Headings, paragraphs, bold/italic, inline code, fenced code blocks, links,
blockquotes, horizontal rules, ordered and unordered lists (nested by indent),
and pipe tables. That is the subset a notes repository actually uses. It is not
a full CommonMark implementation and does not try to be; `check_site.py`
validates the output, so a construct that renders to broken HTML fails the gate
rather than shipping.
"""

from __future__ import annotations

import posixpath
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
REF = DOCS / "reference"

GENERATED_BANNER = "GENERATED by scripts/build_reference.py -- edit the .md source and run `make reference`."


# --------------------------------------------------------------------------- #
# Inline rendering
# --------------------------------------------------------------------------- #

def esc(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


_LINK_RE = re.compile(r"\[([^\]]+)\]\(([^)\s]+)\)")
_CODE_RE = re.compile(r"`([^`]+)`")


def _emphasis(text: str) -> str:
    text = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", text)
    text = re.sub(r"__([^_]+)__", r"<strong>\1</strong>", text)
    text = re.sub(r"(?<![\w*])\*([^*\s][^*]*?)\*(?![\w*])", r"<em>\1</em>", text)
    text = re.sub(r"(?<![\w_])_([^_\s][^_]*?)_(?![\w_])", r"<em>\1</em>", text)
    return text


def _links_and_emphasis(text: str) -> str:
    """Operate on already-escaped text: expand links, then emphasis."""
    out: list[str] = []
    pos = 0
    for m in _LINK_RE.finditer(text):
        out.append(_emphasis(text[pos:m.start()]))
        out.append(f'<a href="{m.group(2)}">{_emphasis(m.group(1))}</a>')
        pos = m.end()
    out.append(_emphasis(text[pos:]))
    return "".join(out)


def render_inline(text: str) -> str:
    """Render inline markdown. Code spans are escaped but never further parsed."""
    out: list[str] = []
    pos = 0
    for m in _CODE_RE.finditer(text):
        out.append(_links_and_emphasis(esc(text[pos:m.start()])))
        out.append(f"<code>{esc(m.group(1))}</code>")
        pos = m.end()
    out.append(_links_and_emphasis(esc(text[pos:])))
    return "".join(out)


# --------------------------------------------------------------------------- #
# Block rendering
# --------------------------------------------------------------------------- #

_HEADING_RE = re.compile(r"^(#{1,6})\s+(.*)$")
_HR_RE = re.compile(r"^\s*(-{3,}|\*{3,}|_{3,})\s*$")
_UL_RE = re.compile(r"^(\s*)[-*]\s+(.*)$")
_OL_RE = re.compile(r"^(\s*)\d+\.\s+(.*)$")
_BQ_RE = re.compile(r"^>\s?(.*)$")
_FENCE_RE = re.compile(r"^```(.*)$")


def _is_table_sep(line: str) -> bool:
    cells = [c.strip() for c in line.strip().strip("|").split("|")]
    cells = [c for c in cells if c != ""]
    return bool(cells) and all(re.fullmatch(r":?-{2,}:?", c) for c in cells)


def _is_block_start(line: str) -> bool:
    return bool(
        _HEADING_RE.match(line)
        or _HR_RE.match(line)
        or _UL_RE.match(line)
        or _OL_RE.match(line)
        or _BQ_RE.match(line)
        or _FENCE_RE.match(line)
        or (line.startswith("```"))
    )


def _split_row(line: str) -> list[str]:
    return [c.strip() for c in line.strip().strip("|").split("|")]


def _build_list(raw: list[tuple[int, bool, str]], pos: int, base: int) -> tuple[str, int]:
    tag = "ol" if raw[pos][1] else "ul"
    out = [f"<{tag}>"]
    while pos < len(raw):
        indent, _ordered, content = raw[pos]
        if indent < base:
            break
        li = "<li>" + render_inline(content)
        pos += 1
        if pos < len(raw) and raw[pos][0] > base:
            child, pos = _build_list(raw, pos, raw[pos][0])
            li += child
        li += "</li>"
        out.append(li)
    out.append(f"</{tag}>")
    return "".join(out), pos


def render_blocks(md: str) -> str:
    lines = md.split("\n")
    i, n = 0, len(md.split("\n"))
    out: list[str] = []
    while i < n:
        line = lines[i]

        if _FENCE_RE.match(line):
            i += 1
            buf: list[str] = []
            while i < n and not lines[i].startswith("```"):
                buf.append(lines[i])
                i += 1
            i += 1  # closing fence
            out.append(f"<pre><code>{esc(chr(10).join(buf))}</code></pre>")
            continue

        if line.strip() == "":
            i += 1
            continue

        m = _HEADING_RE.match(line)
        if m:
            level = len(m.group(1))
            out.append(f"<h{level}>{render_inline(m.group(2).strip())}</h{level}>")
            i += 1
            continue

        if _HR_RE.match(line):
            out.append("<hr>")
            i += 1
            continue

        if _BQ_RE.match(line):
            buf = []
            while i < n and _BQ_RE.match(lines[i]):
                buf.append(_BQ_RE.match(lines[i]).group(1))
                i += 1
            out.append(f"<blockquote>{render_blocks(chr(10).join(buf))}</blockquote>")
            continue

        if "|" in line and i + 1 < n and "|" in lines[i + 1] and _is_table_sep(lines[i + 1]):
            header = _split_row(line)
            i += 2  # header + separator
            body: list[list[str]] = []
            while i < n and lines[i].strip() != "" and "|" in lines[i]:
                body.append(_split_row(lines[i]))
                i += 1
            head_html = "".join(f"<th>{render_inline(c)}</th>" for c in header)
            rows_html = "".join(
                "<tr>" + "".join(f"<td>{render_inline(c)}</td>" for c in row) + "</tr>"
                for row in body
            )
            out.append(
                '<div class="table-scroll"><table><thead><tr>'
                + head_html
                + "</tr></thead><tbody>"
                + rows_html
                + "</tbody></table></div>"
            )
            continue

        if _UL_RE.match(line) or _OL_RE.match(line):
            raw: list[tuple[int, bool, str]] = []
            while i < n:
                mu, mo = _UL_RE.match(lines[i]), _OL_RE.match(lines[i])
                if mu:
                    raw.append((len(mu.group(1)), False, mu.group(2)))
                    i += 1
                elif mo:
                    raw.append((len(mo.group(1)), True, mo.group(2)))
                    i += 1
                elif lines[i].strip() == "" and i + 1 < n and (_UL_RE.match(lines[i + 1]) or _OL_RE.match(lines[i + 1])):
                    i += 1
                elif lines[i].startswith((" ", "\t")) and raw and lines[i].strip() != "":
                    ind, ordered, content = raw[-1]
                    raw[-1] = (ind, ordered, content + " " + lines[i].strip())
                    i += 1
                else:
                    break
            block, _ = _build_list(raw, 0, raw[0][0])
            out.append(block)
            continue

        # paragraph
        buf = []
        while i < n and lines[i].strip() != "" and not _is_block_start(lines[i]):
            buf.append(lines[i].strip())
            i += 1
        out.append(f"<p>{render_inline(' '.join(buf))}</p>")

    return "\n".join(out)


# --------------------------------------------------------------------------- #
# Document model
# --------------------------------------------------------------------------- #

@dataclass
class Doc:
    docs_rel: str            # e.g. "reference/notes/error-analysis.md"
    title: str
    description: str
    body_md: str             # markdown with the title line and lede paragraph removed

    @property
    def html_rel(self) -> str:
        return self.docs_rel[:-3] + ".html"


def parse_doc(md_path: Path) -> Doc:
    text = md_path.read_text().replace("\r\n", "\n")
    lines = text.split("\n")

    title = md_path.stem.replace("-", " ").replace("_", " ").title()
    description = ""
    body_start = 0

    # Title: first H1.
    for idx, line in enumerate(lines):
        if line.strip() == "":
            continue
        h1 = re.match(r"^#\s+(.*)$", line)
        if h1:
            title = h1.group(1).strip()
            body_start = idx + 1
        break

    # Description: first paragraph after the title.
    idx = body_start
    while idx < len(lines) and lines[idx].strip() == "":
        idx += 1
    if idx < len(lines) and not _is_block_start(lines[idx]):
        para = []
        while idx < len(lines) and lines[idx].strip() != "" and not _is_block_start(lines[idx]):
            para.append(lines[idx].strip())
            idx += 1
        description = " ".join(para)
        body_start = idx

    body_md = "\n".join(lines[body_start:]).strip("\n")
    docs_rel = md_path.resolve().relative_to(DOCS).as_posix()
    return Doc(docs_rel=docs_rel, title=title, description=description, body_md=body_md)


# --------------------------------------------------------------------------- #
# Content discovery
# --------------------------------------------------------------------------- #

@dataclass
class Section:
    key: str
    label: str
    blurb: str
    docs: list[Doc] = field(default_factory=list)


def _published_md(path: Path) -> bool:
    return path.suffix == ".md" and not path.name.startswith("_") and path.name != "README.md"


def discover() -> list[Section]:
    sections = [
        Section("resources", "Resources", "Annotated reading list, mapped to the lessons."),
        Section("notes", "Notes", "What I am learning about evals, written up as I go."),
        Section("interview", "Interview Q&A", "Questions and answers, refined over time."),
    ]
    by_key = {s.key: s for s in sections}

    res = REF / "resources.md"
    if res.exists():
        by_key["resources"].docs.append(parse_doc(res))

    for key in ("notes", "interview"):
        folder = REF / key
        if folder.is_dir():
            for md in sorted(folder.glob("*.md")):
                if _published_md(md):
                    by_key[key].docs.append(parse_doc(md))

    for s in sections:
        s.docs.sort(key=lambda d: (d.title.lower(), d.docs_rel))
    return sections


# --------------------------------------------------------------------------- #
# HTML template
# --------------------------------------------------------------------------- #

def rel(from_docs_rel: str, to_docs_rel: str) -> str:
    from_dir = posixpath.dirname(from_docs_rel) or "."
    return posixpath.relpath(to_docs_rel, from_dir)


def page(docs_rel: str, *, kicker: list[str], title: str, lede: str,
         crumb: str, body_html: str) -> str:
    css = rel(docs_rel, "assets/course.css")
    js = rel(docs_rel, "assets/theme.js")
    home = rel(docs_rel, "index.html")
    kicker_html = '<span class="dot">/</span>'.join(f"<span>{esc(k)}</span>" for k in kicker)
    lede_html = f'\n    <p class="lede">{render_inline(lede)}</p>' if lede else ""
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{esc(title)}</title>
<link rel="stylesheet" href="{css}">
</head>
<body>
<!-- {GENERATED_BANNER} -->

<div class="topbar">
  <div class="topbar-in">
    <a class="brand" href="{home}">Wayfarer Evals</a>
    <span class="crumb">{crumb}</span>
    <span class="spacer"></span>
    <button class="theme-btn" id="theme">theme</button>
  </div>
</div>

<div class="wrap narrow">

  <header class="masthead">
    <div class="kicker">
      {kicker_html}
    </div>
    <h1>{esc(title)}</h1>{lede_html}
  </header>

{body_html}

  <footer>
    Method credit: <b>AI Evals for Engineers &amp; PMs</b> by Hamel Husain and Shreya Shankar.
    Independent implementation, MIT licensed.
  </footer>

</div>

<script src="{js}"></script>
</body>
</html>
"""


def crumb_for(docs_rel: str, trail: list[str]) -> str:
    """trail is a list of (label) with the last being the current, unlinked page."""
    course = rel(docs_rel, "index.html")
    ref_home = rel(docs_rel, "reference/index.html")
    parts = [f'<a href="{course}">Course</a>']
    if trail[:-1]:  # something between Course and here
        parts.append(f'<a href="{ref_home}">Reference</a>')
        parts.extend(esc(t) for t in trail[:-1] if t != "Reference")
    parts.append(esc(trail[-1]))
    return " &rsaquo; ".join(parts)


# --------------------------------------------------------------------------- #
# Rendering the pages
# --------------------------------------------------------------------------- #

def render_entry(doc: Doc, section_label: str) -> str:
    # No per-line indentation: newlines inside <pre> are significant, and
    # indenting them would inject stray leading spaces into code blocks.
    body = f'  <div class="slot">\n{render_blocks(doc.body_md)}\n  </div>'
    crumb = crumb_for(doc.html_rel, ["Reference", section_label])
    return page(
        doc.html_rel,
        kicker=["Reference", section_label],
        title=doc.title,
        lede=doc.description,
        crumb=crumb,
        body_html=body,
    )


def _home_intro_md() -> str:
    intro = REF / "_home.md"
    if intro.exists():
        return intro.read_text().replace("\r\n", "\n").strip("\n")
    return "# Reference & notes\n\nA living reference on evaluating LLM products."


def render_home_html(sections: list[Section]) -> str:
    docs_rel = "reference/index.html"
    intro_md = _home_intro_md()
    intro_lines = intro_md.split("\n")
    title = "Reference & notes"
    lede = ""
    body_start = 0
    m = re.match(r"^#\s+(.*)$", intro_lines[0]) if intro_lines else None
    if m:
        title = m.group(1).strip()
        body_start = 1
    idx = body_start
    while idx < len(intro_lines) and intro_lines[idx].strip() == "":
        idx += 1
    if idx < len(intro_lines) and not _is_block_start(intro_lines[idx]):
        para = []
        while idx < len(intro_lines) and intro_lines[idx].strip() != "" and not _is_block_start(intro_lines[idx]):
            para.append(intro_lines[idx].strip())
            idx += 1
        lede = " ".join(para)
        body_start = idx
    intro_body = render_blocks("\n".join(intro_lines[body_start:]).strip("\n"))

    parts = [f'  <div class="slot">\n  {intro_body}\n  </div>'] if intro_body.strip() else []

    for s in sections:
        cards = []
        for d in s.docs:
            href = rel(docs_rel, d.html_rel)
            desc = f'<p style="font-size:14.5px;color:var(--text-2)">{render_inline(d.description)}</p>' if d.description else ""
            cards.append(
                f'      <div class="card">\n'
                f'        <h3 style="margin-bottom:8px"><a href="{href}">{esc(d.title)}</a></h3>\n'
                f'        {desc}\n'
                f'      </div>'
            )
        if not cards:
            cards.append(
                f'      <div class="card">\n'
                f'        <p style="font-size:14.5px;color:var(--text-3)">Nothing here yet.</p>\n'
                f'      </div>'
            )
        grid = '\n'.join(cards)
        parts.append(
            f'  <section>\n'
            f'    <div class="sec-head">\n'
            f'      <h2>{esc(s.label)}</h2>\n'
            f'      <span class="tag">{esc(s.blurb)}</span>\n'
            f'    </div>\n'
            f'    <div class="grid-2">\n{grid}\n    </div>\n'
            f'  </section>'
        )

    body_html = "\n\n".join(parts)
    return page(
        docs_rel,
        kicker=["Reference", "Living document"],
        title=title,
        lede=lede,
        crumb=crumb_for(docs_rel, ["Reference"]),
        body_html=body_html,
    )


def render_home_md(sections: list[Section]) -> str:
    lines = [f"<!-- {GENERATED_BANNER} -->", "", _home_intro_md(), ""]
    for s in sections:
        lines.append(f"## {s.label}")
        lines.append("")
        if not s.docs:
            lines.append("_Nothing here yet._")
            lines.append("")
            continue
        for d in s.docs:
            md_href = rel("reference/README.md", d.docs_rel)
            suffix = f" — {d.description}" if d.description else ""
            lines.append(f"- [{d.title}]({md_href}){suffix}")
        lines.append("")
    lines.append("---")
    lines.append("")
    lines.append(f"_This file is generated. Edit the markdown sources and run `make reference`._")
    lines.append("")
    return "\n".join(lines)


# --------------------------------------------------------------------------- #
# Build / check
# --------------------------------------------------------------------------- #

def compute_outputs() -> dict[Path, str]:
    sections = discover()
    outputs: dict[Path, str] = {}
    outputs[REF / "index.html"] = render_home_html(sections)
    outputs[REF / "README.md"] = render_home_md(sections)
    for s in sections:
        for d in s.docs:
            outputs[DOCS / d.html_rel] = render_entry(d, s.label)
    return outputs


def main(argv: list[str]) -> int:
    check = "--check" in argv
    if not REF.exists():
        print(f"no reference directory at {REF.relative_to(ROOT)}; nothing to build")
        return 0

    outputs = compute_outputs()

    if check:
        stale: list[str] = []
        for path, content in outputs.items():
            current = path.read_text() if path.exists() else None
            if current != content:
                stale.append(str(path.relative_to(ROOT)))
        if stale:
            print(f"{len(stale)} generated file(s) out of date with their markdown source:")
            for s in stale:
                print(f"  {s}")
            print("\nrun `make reference` and commit the result.")
            return 1
        print(f"reference in sync: {len(outputs)} generated file(s) match their source")
        return 0

    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
    print(f"wrote {len(outputs)} file(s) under {REF.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
