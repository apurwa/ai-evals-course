"""Structural checks on the course site. No browser, no network.

Run:  python scripts/check_site.py

A broken link in a course is worse than a broken link on a marketing page,
because the reader assumes they misunderstood something rather than that the
page is wrong. These are the failures that are cheap to catch mechanically and
expensive to catch by clicking:

  - a lesson or lab that links to a page nobody wrote
  - a page referencing a stylesheet, script or data file that is not there
  - a lab whose data file exists but is not wired into `make check`, so it goes
    stale silently
  - a page that loads data by fetch(), which breaks the file:// promise that
    Track A is built on
  - unbalanced tags, which render as something plausible and wrong

What this does NOT check is whether the JavaScript in a lab actually works.
That needs a browser. Treat a pass here as "the site is wired up correctly",
never as "the labs behave".
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"

# Tags that legitimately never close.
VOID = {"area", "base", "br", "col", "embed", "hr", "img", "input", "link",
        "meta", "param", "source", "track", "wbr", "!doctype"}


def check_links(page: Path, html: str, problems: list[str]) -> None:
    for m in re.finditer(r'(?:href|src)="([^"]+)"', html):
        target = m.group(1)
        if target.startswith(("http://", "https://", "#", "mailto:", "data:")):
            continue
        clean = target.split("#")[0].split("?")[0]
        if not clean:
            continue
        resolved = (page.parent / clean).resolve()
        if not resolved.exists():
            problems.append(f"{page.relative_to(ROOT)}: broken reference -> {target}")


def check_tags(page: Path, html: str, problems: list[str]) -> None:
    # Ignore anything inside <script>, <style> or comments, where < and > are
    # arithmetic and CSS rather than markup.
    stripped = re.sub(r"<script\b.*?</script>", "", html, flags=re.S | re.I)
    stripped = re.sub(r"<style\b.*?</style>", "", stripped, flags=re.S | re.I)
    stripped = re.sub(r"<!--.*?-->", "", stripped, flags=re.S)

    stack: list[str] = []
    for m in re.finditer(r"<(/?)([a-zA-Z!][a-zA-Z0-9-]*)\b[^>]*?(/?)>", stripped):
        closing, name, selfclose = m.group(1), m.group(2).lower(), m.group(3)
        if name in VOID or selfclose:
            continue
        if closing:
            if not stack:
                problems.append(f"{page.relative_to(ROOT)}: </{name}> with nothing open")
                return
            if stack[-1] != name:
                problems.append(
                    f"{page.relative_to(ROOT)}: </{name}> closes <{stack[-1]}>")
                return
            stack.pop()
        else:
            stack.append(name)
    if stack:
        problems.append(f"{page.relative_to(ROOT)}: never closed: {', '.join(stack)}")


def main() -> int:
    problems: list[str] = []
    pages = sorted(DOCS.rglob("*.html"))
    if len(pages) < 20:
        problems.append(f"only {len(pages)} pages found; expected the full course")

    for page in pages:
        html = page.read_text()
        check_links(page, html, problems)
        check_tags(page, html, problems)

        # Track A's whole promise is that you can open the file from disk. A
        # fetch() of a sibling file is a cross-origin request under file:// and
        # is blocked, so this would fail only for people not running a server,
        # which is exactly the audience the track is for.
        if "fetch(" in html or "XMLHttpRequest" in html:
            problems.append(f"{page.relative_to(ROOT)}: uses fetch/XHR, breaks file://")

        # Offline-first: nothing may be LOADED from another host. An <a href>
        # pointing at github is a link the reader may click, which is fine and
        # is not a load, so only src= and <link href= count here.
        for m in re.finditer(r'<(?:script|img|iframe|source)\b[^>]*\bsrc="(https?://[^"]+)"', html, re.I):
            problems.append(f"{page.relative_to(ROOT)}: loads external resource {m.group(1)}")
        for m in re.finditer(r'<link\b[^>]*\bhref="(https?://[^"]+)"', html, re.I):
            problems.append(f"{page.relative_to(ROOT)}: loads external stylesheet {m.group(1)}")

        if page.name != "index.html" and "<title>" not in html:
            problems.append(f"{page.relative_to(ROOT)}: no <title>")

    # Every committed data file a lab loads must be regenerated by `make check`,
    # or it goes stale without anything failing.
    generated = {"seed-traces", "lab-corpus", "lab-data", "redteam"}
    for js in sorted((DOCS / "data").glob("*.js")):
        if js.stem not in generated:
            problems.append(f"docs/data/{js.name}: not produced by any generator in make check")
    for stem in sorted(generated):
        if not (DOCS / "data" / f"{stem}.js").exists():
            problems.append(f"docs/data/{stem}.js missing; run make check")

    # Every lesson should reach its lab and vice versa, or one of them is
    # orphaned and nobody will find it.
    for lesson in sorted((DOCS / "lessons").glob("*.html")):
        if "../labs/" not in lesson.read_text():
            problems.append(f"{lesson.relative_to(ROOT)}: links to no lab")
    for lab in sorted((DOCS / "labs").glob("*.html")):
        if "../lessons/" not in lab.read_text():
            problems.append(f"{lab.relative_to(ROOT)}: links back to no lesson")

    index = (DOCS / "index.html").read_text()
    for lesson in sorted((DOCS / "lessons").glob("*.html")):
        if f"lessons/{lesson.name}" not in index:
            problems.append(f"{lesson.name} is not linked from the course index")

    print(f"checked {len(pages)} pages")
    if problems:
        print(f"\n{len(problems)} problem(s):")
        for p in problems:
            print(f"  {p}")
        return 1
    print("site structure ok: links resolve, tags balance, no fetch, no external resources")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
